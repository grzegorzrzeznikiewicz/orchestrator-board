import { readFileSync } from "node:fs";
import path from "node:path";
import product from "../../product.json";

export const RELEASE_REPO = product.releaseRepo;
export const RELEASES_URL = `https://github.com/${RELEASE_REPO}/releases`;
export const STAGED_UPDATE_FILE_NAME = `${product.executableName}-staged-update.json`;

export class UpdateSourceError extends Error {
  constructor(detail: string) {
    super(`Orchestrator Board update configuration: ${detail}`);
    this.name = "UpdateSourceError";
  }
}

/** Deliberately accept only the small, flat config generated by our packager. */
export function parseReleaseSource(yml: string): { owner: string; repo: string } {
  const fields = new Map<string, string>();
  for (const line of yml.split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    const match = /^([A-Za-z]+):\s*([A-Za-z0-9._-]+)\s*$/.exec(line);
    if (!match || fields.has(match[1])) throw new UpdateSourceError("invalid bundled app-update.yml.");
    fields.set(match[1], match[2]);
  }
  if ([...fields.keys()].some(key => !["provider", "owner", "repo", "updaterCacheDirName", "channel"].includes(key)) ||
      fields.get("provider") !== "github" ||
      `${fields.get("owner")}/${fields.get("repo")}` !== RELEASE_REPO ||
      fields.get("updaterCacheDirName") !== product.updaterCacheDirName ||
      (fields.has("channel") && !["latest", "nightly"].includes(fields.get("channel")!))) {
    throw new UpdateSourceError("bundled source must name this fork and its update cache.");
  }
  return { owner: fields.get("owner")!, repo: fields.get("repo")! };
}

/** Re-read at each entry point; a previous valid read must not mask a bad bundle. */
export function readReleaseSource(): { owner: string; repo: string } {
  try {
    return parseReleaseSource(readFileSync(path.join(process.resourcesPath, "app-update.yml"), "utf8"));
  } catch (error) {
    if (error instanceof UpdateSourceError) throw error;
    throw new UpdateSourceError("missing or unreadable bundled app-update.yml. Reinstall this fork from its Releases page.");
  }
}

export function assertForkReleaseUrl(value: string): void {
  let url: URL;
  try { url = new URL(value); } catch { throw new UpdateSourceError("invalid release URL."); }
  if (url.protocol !== "https:" || url.host !== "github.com" || url.username || url.password || url.search || url.hash ||
      !url.pathname.startsWith(`/${RELEASE_REPO}/releases/`) || /%|\\/.test(value)) {
    throw new UpdateSourceError("release URL is outside this fork.");
  }
}

/** Metadata may name an asset or an absolute URL under our own releases. */
export function assertForkArtifactReference(value: string): void {
  if (/^[A-Za-z0-9][A-Za-z0-9._+-]*$/.test(value) && value !== "." && value !== "..") return;
  assertForkReleaseUrl(value);
  const url = new URL(value);
  if (!new RegExp(`^/${RELEASE_REPO}/releases/download/[^/]+/[^/]+$`).test(url.pathname)) {
    throw new UpdateSourceError("invalid release artifact URL.");
  }
}
